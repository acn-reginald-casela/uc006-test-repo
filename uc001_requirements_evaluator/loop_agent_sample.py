"""
Sample: iterative "write -> critique -> refine" pipeline using Google ADK's
LoopAgent, served over an HTTP API instead of asking an agent to invent its
own input.

LoopAgent is a workflow agent from the Google Agent Development Kit (ADK) that
runs its sub_agents repeatedly, in order, on every iteration until either:
  - `max_iterations` is reached, or
  - some sub-agent sets `actions.escalate = True` on its context, which the
    LoopAgent treats as a signal to stop.

Escalating can be done from a tool (`tool_context.actions.escalate = True`),
but this sample does it from an `after_agent_callback` on the CriticAgent
instead: the callback runs right after the critic produces its verdict, reads
that verdict straight out of session state, and escalates once every scored
criterion clears the approval threshold -- no dedicated "exit" tool or extra
LLM call required.

Pipeline (root_agent IS the LoopAgent -- no separate agent generates a
starting draft):
  TestCaseRefinementLoop (LoopAgent):
    a. WriterAgent  - on the first pass, drafts test cases straight from the
                       story's requirements/acceptance criteria; on later
                       passes, revises them per the critic's scoring feedback.
    b. CriticAgent  - scores the test cases against a fixed rubric (see
                       CRITERIA below), one score per criterion, as a JSON
                       array. Its after_agent_callback stops the loop once
                       every criterion scores at/above APPROVAL_SCORE_THRESHOLD.

The starting input -- a user story and its acceptance criteria -- comes from
an HTTP POST body instead of being generated by an LLM:

    POST /test-cases
    {
      "story": {
        "id": "US-142",
        "requirements": "As a ..., I want ..., so that ...\\n\\nAcceptance Criteria:\\n  AC-1: ..."
      },
      "session_id": "regie_123"
    }

Install:
    pip install google-adk fastapi uvicorn

Auth:
    Set GOOGLE_API_KEY (AI Studio) or configure Application Default
    Credentials for Vertex AI before running.

Run:
    python loop_agent_sample.py
    # then, from another shell:
    curl -X POST http://localhost:8000/test-cases -H "Content-Type: application/json" -d @request.json
"""

