#   Build the main loop agent
root_agent = build_pipeline()
#   Create the session
session_service = InMemorySessionService()
runner = Runner(agent=root_agent, app_name=APP_NAME, session_service=session_service)

app = FastAPI(title="UC001")

class Story(BaseModel):
    id: str
    requirements: str


class GenerateTestCasesRequest(BaseModel):
    story: Story
    session_id: str


@app.post("/test-cases")
async def generate_test_cases(payload: GenerateTestCasesRequest):
    """Runs the refinement loop against the supplied story and returns the result."""
    user_id = payload.session_id
    session_id = payload.session_id
    rubric_version = {"version": RUBRIC_VERSION}
    rubric = bq.query_table(RUBRIC_TABLE,where=rubric_version,)

    session = await session_service.get_session(
        app_name=APP_NAME, user_id=user_id, session_id=session_id
    )
    if session is None:
        session = await session_service.create_session(
            app_name=APP_NAME,
            user_id=user_id,
            session_id=session_id,
            state={
                StateKey.STORY_ID: payload.story.id,
                StateKey.OPTIMIZER: payload.story.requirements,
                StateKey.EVALUATOR: "",
                StateKey.CRITERIA: rubric
            },
        )

    trigger_message = types.Content(
        role="user", parts=[types.Part(text="Generate the test cases.")]
    )

    async for _event in runner.run_async(
        user_id=user_id, session_id=session_id, new_message=trigger_message
    ):
        pass  # the result we care about lives in session state, not the events

    session = await session_service.get_session(
        app_name=APP_NAME, user_id=user_id, session_id=session_id
    )
    raw_scores = session.state.get(StateKey.EVALUATOR, "")
    try:
        scores = json.loads(raw_scores)
    except (TypeError, ValueError):
        scores = raw_scores  # critic didn't return valid JSON; pass the raw text through

    return {
        "story_id": session.state.get(StateKey.STORY_ID),
        "final_requirement": session.state.get(StateKey.OPTIMIZER),
        "test_cases": session.state.get(StateKey.EVALUATOR),
        "scores": scores,
    }


if __name__ == "__main__":
    import uvicorn

    uvicorn.run(app, host="0.0.0.0", port=8080)
